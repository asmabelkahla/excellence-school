import { Injectable, computed, effect, inject, signal } from '@angular/core';
import { HttpClient } from '@angular/common/http';
import { firstValueFrom, Observable } from 'rxjs';
import { environment } from '../../../environments/environment';
import { AuthService, readableApiError } from './auth.service';

export type Relationship = 'mere' | 'pere' | 'tuteur';

export const RELATIONSHIP_LABELS: Record<Relationship, string> = {
  mere: 'Mère',
  pere: 'Père',
  tuteur: 'Tuteur'
};

export interface ParentChild {
  student_id: string;
  first_name: string;
  last_name: string;
  class_name: string | null;
  relationship: Relationship | string;
}

export interface ParentAccount {
  id: string;
  full_name: string;
  email: string | null;
  phone: string | null;
  active: boolean;
  must_change_password: boolean;
  created_at: string;
  /** pending = self-registered, waiting for a link request to be approved. */
  status: 'active' | 'pending' | 'inactive';
  pending_requests: number;
  children: ParentChild[];
}

export interface ParentInput {
  fullName: string;
  email: string;
  phone: string;
}

export interface ChildLink {
  studentId: string;
  relationship: Relationship;
}

/** Parent accounts through the API (`/parents`). Passwords are generated by the server and shown once. */
@Injectable({ providedIn: 'root' })
export class ParentsApiService {
  private readonly http = inject(HttpClient);
  private readonly api = `${environment.apiUrl}/parents`;

  readonly parents = signal<ParentAccount[]>([]);
  readonly loading = signal(false);
  readonly loaded = signal(false);
  readonly error = signal<string | null>(null);
  readonly pendingCount = computed(() => this.parents().filter(p => p.status === 'pending').length);

  constructor() {
    const auth = inject(AuthService);
    let previousUserId: string | null = null;
    effect(() => {
      const userId = auth.currentUser()?.id ?? null;
      if (previousUserId !== null && userId !== previousUserId) this.reset();
      previousUserId = userId;
    });
  }

  async load(): Promise<void> {
    if (this.loading()) return;
    this.loading.set(true);
    this.error.set(null);
    try {
      this.parents.set(await firstValueFrom(this.http.get<ParentAccount[]>(this.api)));
      this.loaded.set(true);
    } catch (error) {
      this.error.set(readableApiError(error, 'Impossible de charger les parents.'));
    } finally {
      this.loading.set(false);
    }
  }

  /** Returns the one-time password to hand to the parent. */
  async create(input: ParentInput, children: ChildLink[] = []): Promise<{ parent: ParentAccount; temporaryPassword: string }> {
    const phone = input.phone.trim();
    const body = {
      fullName: input.fullName.trim(),
      email: input.email.trim().toLowerCase(),
      ...(phone ? { phone } : {}),
      ...(children.length ? { children } : {})
    };
    const result = await this.call(this.http.post<{ parent: ParentAccount; temporaryPassword: string }>(this.api, body));
    this.upsert(result.parent);
    return result;
  }

  async update(id: string, changes: Partial<ParentInput> & { active?: boolean }): Promise<ParentAccount> {
    const body: Record<string, unknown> = { ...changes };
    if (typeof changes.fullName === 'string') body['fullName'] = changes.fullName.trim();
    if (typeof changes.email === 'string') body['email'] = changes.email.trim().toLowerCase();
    if (typeof changes.phone === 'string') body['phone'] = changes.phone.trim();
    const parent = await this.call(this.http.patch<ParentAccount>(this.url(id), body));
    this.upsert(parent);
    return parent;
  }

  async resetPassword(id: string): Promise<string> {
    const { temporaryPassword } = await this.call(
      this.http.post<{ temporaryPassword: string }>(`${this.url(id)}/reset-password`, {})
    );
    this.parents.update(list => list.map(p => (p.id === id ? { ...p, must_change_password: true } : p)));
    return temporaryPassword;
  }

  async linkChild(id: string, link: ChildLink): Promise<ParentAccount> {
    const parent = await this.call(this.http.post<ParentAccount>(`${this.url(id)}/children`, link));
    this.upsert(parent);
    return parent;
  }

  async unlinkChild(id: string, studentId: string): Promise<ParentAccount> {
    const parent = await this.call(
      this.http.delete<ParentAccount>(`${this.url(id)}/children/${encodeURIComponent(studentId)}`)
    );
    this.upsert(parent);
    return parent;
  }

  reset(): void {
    this.parents.set([]);
    this.loaded.set(false);
    this.error.set(null);
  }

  private url(id: string): string {
    return `${this.api}/${encodeURIComponent(id)}`;
  }

  private upsert(parent: ParentAccount): void {
    this.parents.update(list => {
      const next = list.some(p => p.id === parent.id)
        ? list.map(p => (p.id === parent.id ? parent : p))
        : [...list, parent];
      return next.sort((a, b) => a.full_name.localeCompare(b.full_name, 'fr'));
    });
  }

  private async call<T>(request: Observable<T>): Promise<T> {
    try {
      return await firstValueFrom(request);
    } catch (error) {
      throw new Error(readableApiError(error));
    }
  }
}
