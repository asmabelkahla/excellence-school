import { Injectable, computed, effect, inject, signal } from '@angular/core';
import { HttpClient } from '@angular/common/http';
import { firstValueFrom, Observable } from 'rxjs';
import { environment } from '../../../environments/environment';
import { UserProfile } from '../models/school.model';
import { AuthService, readableApiError } from './auth.service';

export type StaffRole = 'admin' | 'moderator' | 'econome' | 'teacher';

export type StaffMember = Omit<UserProfile, 'password' | 'role'> & { role: StaffRole };

export interface StaffInput {
  fullName: string;
  email: string;
  phone: string;
  role: StaffRole;
}

export const STAFF_ROLE_LABELS: Record<StaffRole, string> = {
  admin: 'Administrateur',
  moderator: 'Modérateur / Site',
  econome: 'Économe',
  teacher: 'Enseignant'
};

/** Staff accounts through the API (`/staff`). Passwords are generated by the server and shown once. */
@Injectable({ providedIn: 'root' })
export class StaffApiService {
  private readonly http = inject(HttpClient);
  private readonly api = `${environment.apiUrl}/staff`;

  readonly staff = signal<StaffMember[]>([]);
  readonly loading = signal(false);
  readonly loaded = signal(false);
  readonly error = signal<string | null>(null);
  readonly activeCount = computed(() => this.staff().filter(s => s.active).length);

  constructor() {
    const auth = inject(AuthService);
    let previousUserId: string | null = null;
    effect(() => {
      const userId = auth.currentUser()?.id ?? null;
      if (previousUserId !== null && userId !== previousUserId) this.reset();
      previousUserId = userId;
    });
  }

  async load(): Promise<void> {
    if (this.loading()) return;
    this.loading.set(true);
    this.error.set(null);
    try {
      this.staff.set(await firstValueFrom(this.http.get<StaffMember[]>(this.api)));
      this.loaded.set(true);
    } catch (error) {
      this.error.set(readableApiError(error, 'Impossible de charger le personnel.'));
    } finally {
      this.loading.set(false);
    }
  }

  /** Returns the one-time password to hand to the new staff member. */
  async create(input: StaffInput): Promise<{ user: StaffMember; temporaryPassword: string }> {
    const result = await this.call(
      this.http.post<{ user: StaffMember; temporaryPassword: string }>(this.api, this.clean(input))
    );
    this.upsert(result.user);
    return result;
  }

  async update(id: string, changes: Partial<StaffInput> & { active?: boolean }): Promise<StaffMember> {
    const body: Record<string, unknown> = { ...changes };
    if (typeof changes.fullName === 'string') body['fullName'] = changes.fullName.trim();
    if (typeof changes.email === 'string') body['email'] = changes.email.trim().toLowerCase();
    if (typeof changes.phone === 'string') body['phone'] = changes.phone.trim();
    const user = await this.call(this.http.patch<StaffMember>(`${this.api}/${encodeURIComponent(id)}`, body));
    this.upsert(user);
    return user;
  }

  async resetPassword(id: string): Promise<string> {
    const { temporaryPassword } = await this.call(
      this.http.post<{ temporaryPassword: string }>(`${this.api}/${encodeURIComponent(id)}/reset-password`, {})
    );
    this.staff.update(list => list.map(s => (s.id === id ? { ...s, must_change_password: true } : s)));
    return temporaryPassword;
  }

  reset(): void {
    this.staff.set([]);
    this.loaded.set(false);
    this.error.set(null);
  }

  private clean(input: StaffInput): Partial<StaffInput> {
    const phone = input.phone.trim();
    return {
      fullName: input.fullName.trim(),
      email: input.email.trim().toLowerCase(),
      role: input.role,
      ...(phone ? { phone } : {})
    };
  }

  private upsert(user: StaffMember): void {
    this.staff.update(list => {
      const next = list.some(s => s.id === user.id) ? list.map(s => (s.id === user.id ? user : s)) : [...list, user];
      return next.sort((a, b) => a.full_name.localeCompare(b.full_name, 'fr'));
    });
  }

  private async call<T>(request: Observable<T>): Promise<T> {
    try {
      return await firstValueFrom(request);
    } catch (error) {
      throw new Error(readableApiError(error));
    }
  }
}
